export function translateText(source: string, locale: Locale): string {
  if (locale === "zh-Hant") return source;
  if (locale === "zh-Hans") {
    return [...source].map((char) => simplifiedCharacters.get(char) ?? char).join("");
  }
  let result = source;
  for (const [from, to] of orderedJapanese) result = result.split(from).join(to);
  return result;
}

export class PageLocalizer {
  locale: Locale;
  private sources = new WeakMap<Text, string>();
  private roots: HTMLElement[];
  private observer: MutationObserver;

  constructor(roots: HTMLElement[]) {
    this.locale = loadLocale();
    this.roots = roots;
    this.observer = new MutationObserver(() => this.refresh());
    for (const root of roots) this.observer.observe(root, { childList: true, subtree: true, characterData: true });
    this.refresh();
  }

  set(locale: Locale): void {
    this.locale = locale;
    saveLocale(locale);
    document.documentElement.lang = locale;
    document.title = translateText("加工所：制高點", locale);
    this.refresh(true);
  }

  refresh(force = false): void {
    for (const root of this.roots) {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let node: Node | null;
      while ((node = walker.nextNode())) {
        const textNode = node as Text;
        if (textNode.parentElement?.closest(".language-switch")) continue;
        let source = this.sources.get(textNode);
        if (source === undefined || (!force && textNode.data !== translateText(source, this.locale))) {
          source = textNode.data;
          this.sources.set(textNode, source);
        }
        const translated = translateText(source, this.locale);
        if (textNode.data !== translated) textNode.data = translated;
      }
      for (const element of root.querySelectorAll<HTMLElement>("[aria-label]")) {
        const source = element.dataset.sourceAriaLabel ?? element.getAttribute("aria-label") ?? "";
        element.dataset.sourceAriaLabel = source;
        element.setAttribute("aria-label", translateText(source, this.locale));
      }
    }
  }
}
